module.exports = {
  installRules,
  getGlobalRuleFiles,
  getLocalRuleFiles,
  mergeRuleFiles,
  installRulesToFile,
  installRulesToFolder,
  REPO_RULES_DIR,
  REPO_LOCAL_RULES_DIR,
  MANAGED_HEADER,
  SECTION_SEPARATOR,
};
